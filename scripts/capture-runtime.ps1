function Assert-MandalaFailureStatus {
    param(
        [Parameter(Mandatory)][string]$Uri,
        [Parameter(Mandatory)][int]$ExpectedStatus,
        [Parameter(Mandatory)][Microsoft.PowerShell.Commands.WebRequestSession]$Session,
        [string]$Method = 'Get',
        [string]$Body,
        [Parameter(Mandatory)][string]$FlowId
    )
    $request = @{
        Uri = $Uri
        Method = $Method
        WebSession = $Session
        Headers = @{ 'X-Mandala-Flow-Id' = $FlowId }
        UseBasicParsing = $true
    }
    if ($Body) {
        $request.ContentType = 'application/json'
        $request.Body = $Body
    }
    $actualStatus = 0
    try {
        $actualStatus = (Invoke-WebRequest @request).StatusCode
    } catch {
        if ($_.Exception.Response -and $_.Exception.Response.StatusCode) {
            $actualStatus = [int]$_.Exception.Response.StatusCode
        } else {
            throw
        }
    }
    if ($actualStatus -ne $ExpectedStatus) {
        throw "Expected HTTP $ExpectedStatus from $Uri, got $actualStatus."
    }
}

try {
    Write-MandalaLog 'Executing real login and CRUD requests.'
    Assert-MandalaFailureStatus -Uri "$baseUrl/api/projects" -ExpectedStatus 401 -Session $userSession -FlowId 'unauthenticated'
