    Invoke-RestMethod -Uri "$baseUrl/api/auth/login" -Method Post -ContentType 'application/json' -Body $userLogin -WebSession $userSession -Headers @{ 'X-Mandala-Flow-Id' = 'login.success' } | Out-Null

    $invalidProject = @{ name = '   ' } | ConvertTo-Json -Compress
    Assert-MandalaFailureStatus -Uri "$baseUrl/api/projects" -ExpectedStatus 400 -Session $userSession -Method Post -Body $invalidProject -FlowId 'project.create.validation'
    Assert-MandalaFailureStatus -Uri "$baseUrl/api/projects/1" -ExpectedStatus 403 -Session $userSession -FlowId 'forbidden'

    $projectBody = @{ name = 'PowerShell runtime capture'; description = 'Generated by capture-runtime.ps1' } | ConvertTo-Json -Compress
    $project = Invoke-RestMethod -Uri "$baseUrl/api/projects" -Method Post -ContentType 'application/json' -Body $projectBody -WebSession $userSession -Headers @{ 'X-Mandala-Flow-Id' = 'project.create.success' }
    $projectId = $project.id
    Invoke-RestMethod -Uri "$baseUrl/api/projects/$projectId" -Method Get -WebSession $userSession -Headers @{ 'X-Mandala-Flow-Id' = 'project.detail' } | Out-Null

    $updatedProject = @{ name = 'PowerShell runtime capture updated'; description = 'Doma update' } | ConvertTo-Json -Compress
    Invoke-RestMethod -Uri "$baseUrl/api/projects/$projectId" -Method Put -ContentType 'application/json' -Body $updatedProject -WebSession $userSession -Headers @{ 'X-Mandala-Flow-Id' = 'project.update' } | Out-Null

    $taskBody = @{ title = 'PowerShell capture task'; description = 'Doma insert' } | ConvertTo-Json -Compress
    $task = Invoke-RestMethod -Uri "$baseUrl/api/projects/$projectId/tasks" -Method Post -ContentType 'application/json' -Body $taskBody -WebSession $userSession -Headers @{ 'X-Mandala-Flow-Id' = 'task.create' }
    $taskId = $task.id
    Invoke-RestMethod -Uri "$baseUrl/api/tasks/$taskId" -Method Get -WebSession $userSession -Headers @{ 'X-Mandala-Flow-Id' = 'task.detail' } | Out-Null

    $updatedTask = @{ title = 'PowerShell capture task updated'; description = 'Doma update'; status = 'IN_PROGRESS' } | ConvertTo-Json -Compress
    Invoke-RestMethod -Uri "$baseUrl/api/tasks/$taskId" -Method Put -ContentType 'application/json' -Body $updatedTask -WebSession $userSession -Headers @{ 'X-Mandala-Flow-Id' = 'task.update' } | Out-Null
    $statusBody = @{ status = 'DONE' } | ConvertTo-Json -Compress
    Invoke-RestMethod -Uri "$baseUrl/api/tasks/$taskId/status" -Method Patch -ContentType 'application/json' -Body $statusBody -WebSession $userSession -Headers @{ 'X-Mandala-Flow-Id' = 'task.status.change' } | Out-Null

    Invoke-WebRequest -Uri "$baseUrl/v3/api-docs" -OutFile (Join-Path $snapshotDir 'openapi.json') -UseBasicParsing
    $adminLogin = @{ username = 'local-admin'; password = 'mandala-admin' } | ConvertTo-Json -Compress
    Invoke-RestMethod -Uri "$baseUrl/api/auth/login" -Method Post -ContentType 'application/json' -Body $adminLogin -WebSession $adminSession | Out-Null
    Invoke-WebRequest -Uri "$baseUrl/actuator/mappings" -WebSession $adminSession -OutFile (Join-Path $snapshotDir 'actuator-mappings.json') -UseBasicParsing
} finally {
    if ($taskId) {
        try { Invoke-RestMethod -Uri "$baseUrl/api/tasks/$taskId" -Method Delete -WebSession $userSession -Headers @{ 'X-Mandala-Flow-Id' = 'task.delete' } | Out-Null } catch { Write-Warning $_ }
    }
