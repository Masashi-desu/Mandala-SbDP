        try { Invoke-RestMethod -Uri "$baseUrl/api/projects/$projectId" -Method Delete -WebSession $userSession -Headers @{ 'X-Mandala-Flow-Id' = 'project.delete' } | Out-Null } catch { Write-Warning $_ }
    }
}

function Get-MandalaSpanAttribute {
    param([Parameter(Mandatory)]$Span, [Parameter(Mandatory)][string]$Key)
    foreach ($attribute in @($Span.attributes)) {
        if ($attribute.key -eq $Key) { return $attribute.value.stringValue }
    }
    return $null
}

function Test-MandalaProjectTrace {
    param([Parameter(Mandatory)][string]$Path)
    $spans = [System.Collections.Generic.List[object]]::new()
    try {
        foreach ($line in Get-Content -LiteralPath $Path) {
            if ([string]::IsNullOrWhiteSpace($line)) { continue }
            $document = $line | ConvertFrom-Json
            foreach ($resourceSpans in @($document.resourceSpans)) {
                foreach ($scopeSpans in @($resourceSpans.scopeSpans)) {
                    foreach ($span in @($scopeSpans.spans)) { $spans.Add($span) }
                }
            }
        }
    } catch {
        return $false
    }
    $projectTraceId = $null
    foreach ($span in $spans) {
        if ((Get-MandalaSpanAttribute -Span $span -Key 'mandala.flow.id') -eq 'project.create.success') {
            $projectTraceId = $span.traceId
            break
        }
    }
    if (-not $projectTraceId) { return $false }
    $layers = @()
    $hasDatabaseSpan = $false
    foreach ($span in $spans) {
        if ($span.traceId -ne $projectTraceId) { continue }
        $layer = Get-MandalaSpanAttribute -Span $span -Key 'mandala.layer'
        if ($layer) { $layers += $layer }
        foreach ($key in 'db.system.name', 'db.system', 'db.operation.name') {
            if (Get-MandalaSpanAttribute -Span $span -Key $key) { $hasDatabaseSpan = $true }
        }
    }
    return $hasDatabaseSpan `
        -and 'http_server' -in $layers `
        -and 'application_service' -in $layers `
        -and 'doma_dao' -in $layers
}

$traceCopied = $false
$candidateTrace = Join-Path ([System.IO.Path]::GetTempPath()) "mandala-otlp-$([guid]::NewGuid().ToString('N')).json"
$lastFingerprint = ''
$stableCopies = 0
for ($attempt = 1; $attempt -le 30; $attempt++) {
    Remove-Item -LiteralPath $candidateTrace -Force -ErrorAction SilentlyContinue
    try {
        Invoke-MandalaCompose cp 'otel-collector:/var/lib/mandala-traces/otlp.json' $candidateTrace
    } catch {
        # The file exporter has not flushed its first batch yet.
    }
    if ((Test-Path -LiteralPath $candidateTrace) -and (Get-Item -LiteralPath $candidateTrace).Length -gt 0) {
        $validJsonLines = $true
        foreach ($line in Get-Content -LiteralPath $candidateTrace) {
            if ([string]::IsNullOrWhiteSpace($line)) { continue }
            try { $line | ConvertFrom-Json | Out-Null } catch { $validJsonLines = $false; break }
        }
        if ($validJsonLines -and (Test-MandalaProjectTrace -Path $candidateTrace)) {
            $fingerprint = (Get-FileHash -LiteralPath $candidateTrace -Algorithm SHA256).Hash
            if ($fingerprint -eq $lastFingerprint) {
                $stableCopies++
            } else {
                $lastFingerprint = $fingerprint
                $stableCopies = 1
            }
            # Cross a complete quiet window after the first reference trace so
            # late Java batch-processor exports cannot leave a detached trace.
            if ($stableCopies -ge 8) {
                Copy-Item -LiteralPath $candidateTrace -Destination $traceFile -Force
                $traceCopied = $true
                break
            }
        } else {
            $lastFingerprint = ''
            $stableCopies = 0
        }
    }
    Start-Sleep -Seconds 1
}
Remove-Item -LiteralPath $candidateTrace -Force -ErrorAction SilentlyContinue
if (-not $traceCopied) {
    throw "Collector did not write a complete and stable project-create OTLP trace to $traceFile. Check .runtime/logs/backend.log and Docker logs."
}
$traceText = Get-Content -LiteralPath $traceFile -Raw
if ($traceText -match '(?i)mandala-(admin|user)|bearer\s+[a-z0-9._-]{8,}|"key"\s*:\s*"[^"]*(authorization|cookie|password|token)[^"]*"') {
    throw 'A local credential or sensitive header was found in the captured trace.'
}

if (-not (Test-MandalaProjectTrace -Path $traceFile)) {
    throw 'Project-create trace does not contain HTTP, service, DAO and database spans in one trace.'
}

$openApi = Get-Content -LiteralPath (Join-Path $snapshotDir 'openapi.json') -Raw | ConvertFrom-Json
if (@($openApi.paths.PSObject.Properties).Count -lt 10) { throw 'Captured OpenAPI contains fewer than 10 paths.' }
$mappings = Get-Content -LiteralPath (Join-Path $snapshotDir 'actuator-mappings.json') -Raw | ConvertFrom-Json
if (-not $mappings.contexts) { throw 'Captured Actuator mappings do not contain contexts.' }
Write-MandalaLog 'Runtime traces, OpenAPI and Actuator mappings captured.'
